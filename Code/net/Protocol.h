// Wire-protocol constants shared by the legacy transport and the asio
// transport. Nothing in this header may depend on sockets or host APIs.

#include <cstddef>
#include <cstdint>

// Listening ports.
#define GAME_PORT   8281
#define DB_PORT     7514
#define ADMIN_PORT  8895

// Transport limits preserved from the legacy transport.
#define MAX_PENDING_CONNECTS 8
#define RECV_BUFFER_SIZE     (128*1024)
#define SEND_BUFFER_SIZE     (128*1024)
#define MAX_MESSAGE_SIZE     8192

// Four-byte handshake sent by outbound game/DB/admin links.
#define INITCODE 0x1F11F311

// Wire header. Only the first four bytes travel in clear; bytes 4.. are
// transformed with the keyword table.
typedef struct _HEADER
{
	short          Size;
	char           KeyWord;
	char           CheckSum;
	short          Type;
	short          ID;
	unsigned int   ClientTick;
} HEADER, *PHEADER;

static_assert(sizeof(HEADER) == 12, "wire header must stay 12 bytes");

// Billing link: unframed 196-byte records.
struct _AUTH_GAME
{
	char Unk[196];
};

#define g_cGame (sizeof(_AUTH_GAME))

constexpr std::size_t BILLING_RECORD_SIZE = 196;

static_assert(sizeof(_AUTH_GAME) == 196, "billing record must stay 196 bytes");

